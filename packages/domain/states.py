from packages.domain.core import DomainError

TERMINAL = {
    "NO_TUNING_REQUIRED",
    "MANUAL_REVIEW_REQUIRED",
    "SUCCEEDED",
    "STOPPED_NO_IMPROVEMENT",
    "STOPPED_MAX_ITERATIONS",
    "STOPPED_TIMEOUT",
    "FAILED_FINAL",
    "CANCELLED",
}
EDGES = {
    "CREATED": {"DATA_LOADING"},
    "DATA_LOADING": {"MONITOR_REQUESTED"},
    "MONITOR_REQUESTED": {"MONITOR_COMPLETED"},
    "MONITOR_COMPLETED": {"NO_TUNING_REQUIRED", "BASELINE_REQUESTED"},
    "BASELINE_REQUESTED": {"BASELINE_RUNNING"},
    "BASELINE_RUNNING": {"BASELINE_COMPLETED"},
    "BASELINE_COMPLETED": {"SUCCEEDED", "CANDIDATE_REQUESTED"},
    "CANDIDATE_REQUESTED": {"CANDIDATE_VALIDATED"},
    "CANDIDATE_VALIDATED": {"TRIAL_REQUESTED"},
    "TRIAL_REQUESTED": {"TRIAL_RUNNING"},
    "TRIAL_RUNNING": {"TRIAL_COMPLETED"},
    "TRIAL_COMPLETED": {"EVALUATING"},
    "EVALUATING": {"CANDIDATE_ACCEPTED", "CANDIDATE_REJECTED"},
    "CANDIDATE_ACCEPTED": {"CANDIDATE_REQUESTED", "SUCCEEDED", "STOPPED_MAX_ITERATIONS"},
    "CANDIDATE_REJECTED": {
        "CANDIDATE_REQUESTED",
        "STOPPED_NO_IMPROVEMENT",
        "STOPPED_MAX_ITERATIONS",
    },
}
FAILURE = {"MANUAL_REVIEW_REQUIRED", "STOPPED_TIMEOUT", "FAILED_FINAL", "CANCELLED"}


def transition(old: str, new: str):
    if old in TERMINAL or (new not in EDGES.get(old, set()) and new not in FAILURE):
        raise DomainError("RUN_STATE_CONFLICT", f"{old} -> {new}")
